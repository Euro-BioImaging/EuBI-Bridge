"""Build eubi-bridge-lite: the same eubi_bridge package as eubi-bridge,
without Bio-Formats (the bundled JARs and JDK) and with only the lite
dependencies.

    python tools/build_lite.py              # sdist + wheel into dist/
    python tools/build_lite.py --keep       # also keep the staging folder

The staging folder gets a copy of eubi_bridge/ without bioformats/, the README
and the licence, and a pyproject.toml written from this repository's: the
name, description, Python range and dependencies from
[tool.eubi-bridge.lite], everything else (version, authors, licence, commands,
package data) from [project].  It builds with plain setuptools: no JDK is
downloaded.  The wheel is built from the sdist, which checks the sdist is
complete.

Needs the `build` package (pip install build).
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = "eubi_bridge"

#: Left out of the copy: Bio-Formats (JARs + JDK) and build / cache debris.
EXCLUDE = ("bioformats", "__pycache__", "*.pyc", "*.pyo", "node_modules")

#: Package data, as in the main pyproject minus "bioformats/**".
PACKAGE_DATA = ["qt_gui/server/**", "qt_gui/*.webp"]


def _toml(value) -> str:
    """A TOML value from a str / list of str (JSON strings are valid TOML)."""
    if isinstance(value, list):
        return "[\n" + "".join(f"    {json.dumps(v)},\n" for v in value) + "]"
    return json.dumps(value)


def lite_pyproject(project: dict, lite: dict) -> str:
    authors = ", ".join(
        "{ " + ", ".join(f"{k} = {json.dumps(v)}" for k, v in a.items()) + " }"
        for a in project.get("authors", []))
    minor = range(11, 15)                          # the Python versions lite is tested on
    classifiers = [f"Programming Language :: Python :: 3.{m}" for m in minor]
    lines = [
        "# Generated by tools/build_lite.py from the eubi-bridge pyproject.toml.",
        "[build-system]",
        'requires = ["setuptools>=77", "wheel"]',
        'build-backend = "setuptools.build_meta"',
        "",
        "[project]",
        f"name = {_toml(lite['name'])}",
        f"version = {_toml(project['version'])}",
        f"description = {_toml(lite['description'])}",
        f"readme = {_toml(project['readme'])}",
        f"requires-python = {_toml(lite['requires-python'])}",
        f"authors = [{authors}]",
        f"license = {_toml(project['license'])}",
        f"dependencies = {_toml(lite['dependencies'])}",
        f"classifiers = {_toml(classifiers)}",
        "",
        "[project.scripts]",
        *(f"{k} = {_toml(v)}" for k, v in project["scripts"].items()),
        "",
        "[project.urls]",
        *(f"{k} = {_toml(v)}" for k, v in project.get("urls", {}).items()),
        "",
        "[tool.setuptools.packages.find]",
        f'include = ["{PACKAGE}", "{PACKAGE}.*"]',
        "",
        "[tool.setuptools.package-data]",
        f"{PACKAGE} = {_toml(PACKAGE_DATA)}",
        "",
    ]
    return "\n".join(lines)


def stage(staging: Path) -> None:
    config = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    project, lite = config["project"], config["tool"]["eubi-bridge"]["lite"]
    shutil.copytree(ROOT / PACKAGE, staging / PACKAGE, ignore=shutil.ignore_patterns(*EXCLUDE))
    for name in (project["readme"], "LICENSE"):
        shutil.copy2(ROOT / name, staging / name)
    (staging / "pyproject.toml").write_text(lite_pyproject(project, lite), encoding="utf-8")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--outdir", default=str(ROOT / "dist"), help="where the sdist and wheel go")
    parser.add_argument("--keep", action="store_true", help="keep the staging folder")
    args = parser.parse_args(argv)

    staging = Path(tempfile.mkdtemp(prefix="eubi_bridge_lite_"))
    try:
        stage(staging)
        print(f"staged in {staging}")
        subprocess.run([sys.executable, "-m", "build", "--outdir", args.outdir, str(staging)],
                       check=True)
    finally:
        if args.keep:
            print(f"kept {staging}")
        else:
            shutil.rmtree(staging, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
